import os
import sys
import joblib
import numpy as np
import torch

# .pyファイルがあるフォルダ
PROJECT_DIR = "~/training"

if PROJECT_DIR not in sys.path:
    sys.path.insert(0, PROJECT_DIR)

print("cdr", os.getcwd())

from config import (
    CACHE_PKL,
    PCA_PATH,
    BEST_PATH,
    NPZ_PATH,
    LEARNING_RATE,
    EPOCHS,
    BETA_KL,
    EARLY_STOP_PATIENCE,
    COLORS,
)
from dataset import load_cached_dataset, create_dataloaders
from model import VAEHarmNoise
from train import train_epoch, eval_epoch
from visualize import plot_latent_progress

def main():
    # データ読み込み
    dataset, label_to_id, id_to_label = load_cached_dataset(CACHE_PKL)
    train_loader, val_loader = create_dataloaders(dataset)

    # shape確認
    xb, cb, yb, y_cls = next(iter(train_loader))
    print("batch shapes:", xb.shape, cb.shape, yb.shape, y_cls.shape)

    # モデル準備
    device = torch.device("cuda" if torch.cuda.is_available() else "cpu")
    print("device:", device)

    model = VAEHarmNoise().to(device)
    optimizer = torch.optim.Adam(model.parameters(), lr=LEARNING_RATE)

    best = float("inf")
    epoch = 0
    count = 0

    while epoch < EPOCHS and count < EARLY_STOP_PATIENCE:
        train_loss = train_epoch(
            model,
            train_loader,
            optimizer,
            device,
            beta_kl=BETA_KL,
        )
        valid_metrics = eval_epoch(
            model,
            val_loader,
            device,
            beta_kl=BETA_KL,
        )
        valid_loss = valid_metrics["loss"]

        print(
            f"[{epoch:02d}] "
            f"train_loss={train_loss:.4f}  "
            f"valid_loss={valid_loss:.4f}"
        )

        # 潜在空間を可視化
        Z, Z2, Y, pca = plot_latent_progress(
            model,
            train_loader,
            id_to_label,
            epoch,
            COLORS,
            device,
            title=f"PCA latent @ epoch {epoch}",
            max_batches=None,
        )
        if Y is not None:
            print(len(Y))

        # best更新時に保存
        if valid_loss < best:
            best = valid_loss

            if BEST_PATH:
                torch.save(model.state_dict(), BEST_PATH)
                print("  ↳ best updated, saved to", BEST_PATH)

            if NPZ_PATH and Z is not None:
                np.savez(
                    NPZ_PATH,
                    Z=Z,
                    Z2=Z2,
                    y_labels=Y,
                    label_to_id=label_to_id,
                    colors=COLORS,
                )
                print("  ↳ npz, saved to", NPZ_PATH)

            if PCA_PATH and pca is not None:
                joblib.dump(pca, PCA_PATH)
                print("[PCA] Saved to", PCA_PATH)

            count = 0
        else:
            count += 1

        epoch += 1


if __name__ == "__main__":
    main()